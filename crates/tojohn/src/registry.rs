/// Look up an extractor by its canonical name.
pub fn by_name(name: &str) -> Option<Box<dyn Extractor>> {
    all().into_iter().find(|e| e.name() == name)
}

/// Canonical names of every supported format.
pub fn names() -> Vec<&'static str> {
    all().iter().map(|e| e.name()).collect()
}
